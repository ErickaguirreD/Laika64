// LAIKA 64 - builds platform/xbox360/xb_emojis.h: the emojis of the online play's quick chat.
// Twemoji graphics (Twitter, CC BY 4.0; the @twemoji/svg package), drawn at EMOJI_SIZE, RGBA.
// A message of the quick chat that is one emoji travels as "@e<n>" (n: its place in this list).
// Run from this folder:  npm install && node make_emojis.js
const fs = require("fs");
const path = require("path");
const { Resvg } = require("@resvg/resvg-js");

const EMOJI_SIZE = 48;
// grinning, tears of joy, sunglasses, thinking, astonished, crying, angry, party, thumbs up, thumbs down, clap, heart, fire, trophy
const EMOJIS = ["1f600", "1f602", "1f60e", "1f914", "1f62e", "1f622", "1f621", "1f973", "1f44d", "1f44e", "1f44f", "2764", "1f525", "1f3c6"];
const dir = path.dirname(require.resolve("@twemoji/svg/package.json"));
let h = "// GENERATED by tools/avatars/make_emojis.js - do not edit.\n" +
  "// The quick chat's emojis: Twemoji (Twitter, CC BY 4.0), RGBA " + EMOJI_SIZE + "x" + EMOJI_SIZE + ".\n" +
  "#ifndef XB_EMOJIS_H\n#define XB_EMOJIS_H\n\n" +
  `#define EMOJI_SIZE ${EMOJI_SIZE}\n#define EMOJI_COUNT ${EMOJIS.length}\n\n` +
  "static const unsigned char s_emojiRgba[EMOJI_COUNT][EMOJI_SIZE * EMOJI_SIZE * 4] = {\n";
for (const code of EMOJIS) {
  const svg = fs.readFileSync(path.join(dir, code + ".svg"), "utf8");
  const px = new Resvg(svg, { fitTo: { mode: "width", value: EMOJI_SIZE }, background: "rgba(0,0,0,0)" }).render().pixels;
  h += "  { // U+" + code.toUpperCase() + "\n";
  for (let i = 0; i < px.length; i += 48) h += "    " + Array.from(px.subarray(i, i + 48)).join(",") + ",\n";
  h += "  },\n";
}
h += "};\n\n#endif\n";
fs.writeFileSync(path.join(__dirname, "../../platform/xbox360/xb_emojis.h"), h);
console.log(`wrote xb_emojis.h: ${EMOJIS.length} emojis, ${(h.length / 1024).toFixed(0)} KB of source`);
