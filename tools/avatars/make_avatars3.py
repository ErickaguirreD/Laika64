"""LAIKA 64 - the animated avatars (platform/xbox360/xb_avatars3.h).

Microsoft's Fluent Emoji Animated (github.com/microsoft/fluentui-emoji-animated, MIT): each one 16 frames of 64x64
side by side (a 1024x64 strip), round (transparent outside its disc), a palette PNG with alpha. Sets: animals, cars,
space, gaming. Their avatar numbers from AVATAR3_BASE (256).

    python tools/avatars/make_avatars3.py <folder of 128 px GIFs: animales/ autos/ espacio/ gaming/>
"""
import glob
import io
import os
import sys

from PIL import Image, ImageDraw, ImageSequence

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'platform', 'xbox360', 'xb_avatars3.h')
SETS = ['animales', 'autos', 'espacio', 'gaming', 'caras']   # (new sets go at the end: the numbers chosen stay)
N, S = 16, 64


def strip_of(path, mask):
    frames = [fr.convert('RGB') for fr in ImageSequence.Iterator(Image.open(path))]
    strip = Image.new('RGBA', (S * N, S), (0, 0, 0, 0))
    for k in range(N):
        fr = frames[int(k * len(frames) / N)].resize((S, S), Image.LANCZOS).convert('RGBA')
        fr.putalpha(mask)
        strip.paste(fr, (k * S, 0))
    buf = io.BytesIO()
    strip.quantize(colors=255, method=Image.Quantize.FASTOCTREE).save(buf, 'PNG', optimize=True)
    return buf.getvalue()


def main():
    src = sys.argv[1]
    big = Image.new('L', (S * 4, S * 4), 0)
    ImageDraw.Draw(big).ellipse([0, 0, S * 4 - 1, S * 4 - 1], fill=255)
    mask = big.resize((S, S), Image.LANCZOS)
    pngs, names, starts = [], [], []
    for cat in SETS:
        starts.append(len(pngs))
        for p in sorted(glob.glob(os.path.join(src, cat, '*.gif'))):
            pngs.append(strip_of(p, mask))
            names.append(cat + '/' + os.path.basename(p)[:-4])
    starts.append(len(pngs))
    out = ['// GENERATED by tools/avatars/make_avatars3.py - do not edit.',
           '// The online play\'s animated avatars: Fluent Emoji Animated (Microsoft, MIT), each 16 frames of 64x64 side by',
           '// side (a 1024x64 strip), round, a palette PNG - sets: animals, cars, space, gaming.',
           '#ifndef XB_AVATARS3_H', '#define XB_AVATARS3_H', '',
           '#define AVATAR3_SIZE %d' % S, '#define AVATAR3_FRAMES %d' % N,
           '#define AVATAR3_BASE 256   // their avatar numbers: from here', '#define AVATAR3_SETS %d' % len(SETS),
           '#define AVATAR3_COUNT %d' % len(pngs), '',
           'static const unsigned short s_avatar3SetStart[AVATAR3_SETS + 1] = { %s };' % ', '.join(map(str, starts)), '']
    for i, (data, name) in enumerate(zip(pngs, names)):
        out.append('static const unsigned char s_avatar3_%d[%d] = {   // %s' % (i, len(data), name))
        for j in range(0, len(data), 32):
            out.append('    ' + ','.join(str(b) for b in data[j:j + 32]) + ',')
        out.append('};')
    out.append('static const unsigned char *const s_avatar3Png[AVATAR3_COUNT] = { %s };' % ', '.join('s_avatar3_%d' % i for i in range(len(pngs))))
    out.append('static const unsigned int s_avatar3PngSize[AVATAR3_COUNT] = { %s };' % ', '.join('sizeof(s_avatar3_%d)' % i for i in range(len(pngs))))
    out += ['', '#endif', '']
    open(OUT, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
    print(len(pngs), 'avatars,', sum(map(len, pngs)), 'bytes ->', OUT)


if __name__ == '__main__':
    main()
