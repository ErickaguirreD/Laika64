"""LAIKA 64 - the online chats' animated emojis (platform/xbox360/xb_emojis_anim.h).

Microsoft's Fluent Emoji Animated (github.com/microsoft/fluentui-emoji-animated, MIT): for each chat emoji ("@eNN",
xb_emojis.h's 14 then the ones added in 3.6) that has an animation, 16 frames of 48x48 side by side (a 768x48 strip),
a palette PNG with alpha. The 14 first keep their Twemoji picture where Fluent has no animation (thumbs, clapping, trophy);
the added ones are only here (their still picture: the first frame).

    python tools/avatars/make_emojis_anim.py [cache folder]
"""
import io
import os
import sys
import urllib.parse
import urllib.request

from PIL import Image, ImageSequence

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'platform', 'xbox360', 'xb_emojis_anim.h')
N, S = 16, 48
# "@eNN" -> its Fluent name ("" none: the Twemoji picture stays)
EMOJIS = ['Grinning face', 'Face with tears of joy', 'Smiling face with sunglasses', 'Thinking face', 'Face with open mouth', 'Crying face',
          'Pouting face', 'Partying face', '', '', '', 'Red heart', 'Fire', '',
          'Smiling face with heart-eyes', 'Loudly crying face', 'Winking face', 'Exploding head', 'Skull', 'Hundred points', 'Party popper',
          'Rolling on the floor laughing']
OLD = 14   # xb_emojis.h's


def fetch(name, cache):
    fn = name.lower().replace(' ', '_') + '_animated.png'
    path = os.path.join(cache, fn)
    if not os.path.exists(path):
        url = 'https://media.githubusercontent.com/media/microsoft/fluentui-emoji-animated/main/assets/%s/animated/%s' % (
            urllib.parse.quote(name), urllib.parse.quote(fn))
        open(path, 'wb').write(urllib.request.urlopen(url, timeout=60).read())
    return Image.open(path)


def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'tools', 'avatars', '.fluent_cache')
    os.makedirs(cache, exist_ok=True)
    out = ['// GENERATED by tools/avatars/make_emojis_anim.py - do not edit.',
           '// The online chats\' animated emojis: Fluent Emoji Animated (Microsoft, MIT), 16 frames of 48x48 side by side',
           '// (a 768x48 strip), a palette PNG - for "@eNN" as EMOJI_ALL counts them (xb_emojis.h\'s 14 first).',
           '#ifndef XB_EMOJIS_ANIM_H', '#define XB_EMOJIS_ANIM_H', '',
           '#define EMOJI_ANIM_SIZE %d' % S, '#define EMOJI_ANIM_FRAMES %d' % N, '#define EMOJI_ALL %d' % len(EMOJIS), '']
    for i, name in enumerate(EMOJIS):
        if not name:
            continue
        frames = [fr.convert('RGBA') for fr in ImageSequence.Iterator(fetch(name, cache))]
        strip = Image.new('RGBA', (S * N, S), (0, 0, 0, 0))
        for k in range(N):
            strip.paste(frames[int(k * len(frames) / N)].resize((S, S), Image.LANCZOS), (k * S, 0))
        buf = io.BytesIO()
        strip.quantize(colors=255, method=Image.Quantize.FASTOCTREE).save(buf, 'PNG', optimize=True)
        data = buf.getvalue()
        out.append('static const unsigned char s_emojiAnim_%d[%d] = {   // %s' % (i, len(data), name))
        for j in range(0, len(data), 32):
            out.append('    ' + ','.join(str(b) for b in data[j:j + 32]) + ',')
        out.append('};')
    out.append('static const unsigned char *const s_emojiAnimPng[EMOJI_ALL] = { %s };' %
               ', '.join('s_emojiAnim_%d' % i if n else 'NULL' for i, n in enumerate(EMOJIS)))
    out.append('static const unsigned int s_emojiAnimPngSize[EMOJI_ALL] = { %s };' %
               ', '.join('sizeof(s_emojiAnim_%d)' % i if n else '0' for i, n in enumerate(EMOJIS)))
    out += ['', '#endif', '']
    open(OUT, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
    print(sum(1 for n in EMOJIS if n), 'animated emojis ->', OUT)


if __name__ == '__main__':
    main()
