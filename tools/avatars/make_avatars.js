// LAIKA 64 - builds platform/xbox360/xb_avatars.h: the online play's avatars.
//
// The pictures are icons of game-icons.net (CC BY 3.0, from the @iconify-json/game-icons package;
// the About page credits them), each drawn white at AVATAR_SIZE and kept as its alpha only: the
// console draws it over a coloured disc (xb_menu.cpp online_avatar). Run from this folder:
//     npm install && node make_avatars.js
const fs = require("fs");
const path = require("path");
const { Resvg } = require("@resvg/resvg-js");
const set = require("@iconify-json/game-icons/icons.json");

const AVATAR_SIZE = 64;
// [icon, disc colour]: grouped by taste, so the list reads as themes.
const AVATARS = [
  // Animals
  ["wolf-head", 0x5a6b8c], ["fox-head", 0xe0702a], ["cat", 0x8a5cc8], ["sitting-dog", 0xb5793a], ["eagle-head", 0x3f7fbf],
  ["owl", 0x7a5a3a], ["shark-jaws", 0x2f8fb0], ["octopus", 0xc0408a], ["snake", 0x3f9a4a], ["turtle", 0x2f9a6a],
  ["rabbit", 0xd08aa0], ["bear-head", 0x8a5a2a], ["lion", 0xd0a030], ["frog", 0x4fb04f], ["penguin", 0x3a4a6a],
  // Fantasy
  ["dragon-head", 0xc03030], ["unicorn", 0xb060d0], ["wizard-staff", 0x5050c0], ["crossed-swords", 0x7a7a8a], ["visored-helm", 0x6a6a7a],
  ["skull-crossed-bones", 0x303038], ["ghost", 0x7080a0], ["imp-laugh", 0xb03050], ["crown", 0xd0a020], ["magic-swirl", 0x6040c0],
  // Space and machines
  ["rocket", 0x4060d0], ["ufo", 0x30a080], ["robot-golem", 0x607080], ["astronaut-helmet", 0x405070], ["planet-core", 0xd06030],
  ["alien-stare", 0x40b060], ["spaceship", 0x5060a0], ["ringed-planet", 0x9060c0],
  // Sports and racing
  ["soccer-ball", 0x30a050], ["basketball-ball", 0xe07020], ["tennis-racket", 0x80b030], ["boxing-glove", 0xc03030], ["podium-winner", 0xd0a020],
  ["race-car", 0xc02828], ["f1-car", 0x2a8ad0], ["skateboard", 0x9050a0], ["trophy", 0xc09020],
  // Games and music
  ["gamepad", 0x404850], ["joystick", 0xb03040], ["ghost-ally", 0xd0b020], ["alien-bug", 0x30a070], ["dice-six-faces-six", 0xc03030],
  ["guitar", 0xa05020], ["drum", 0xb07030], ["musical-notes", 0x5050c0], ["headphones", 0x303848],
  // Food and things
  ["mushroom-gills", 0xc03030], ["cherry", 0xc02040], ["pizza-slice", 0xd07020], ["cupcake", 0xd070a0], ["star-medal", 0xd0a020],
  ["lightning-trio", 0xd0b020], ["flame", 0xe05020], ["snowflake-1", 0x50a0d0], ["sun", 0xe0a020], ["heart-plus", 0xc03050],
];

const out = [];
const names = [];
const missing = [];
for (const [name, colour] of AVATARS) {
  const icon = set.icons[name];
  if (!icon) { missing.push(name); continue; }
  const w = icon.width || set.width || 512, h = icon.height || set.height || 512;
  // The icon white on nothing, a margin around it so it sits inside the disc.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-w * 0.2} ${-h * 0.2} ${w * 1.4} ${h * 1.4}" width="${AVATAR_SIZE}" height="${AVATAR_SIZE}">` +
    `<g fill="#fff">${icon.body.replace(/fill="#000"/g, 'fill="#fff"').replace(/<path d="M0 0h512v512H0z"\/>/, "")}</g></svg>`;
  const png = new Resvg(svg, { fitTo: { mode: "width", value: AVATAR_SIZE }, background: "rgba(0,0,0,0)" }).render();
  const rgba = png.pixels;
  const alpha = Buffer.alloc(AVATAR_SIZE * AVATAR_SIZE);
  for (let i = 0; i < alpha.length; i++) alpha[i] = rgba[i * 4 + 3];
  out.push({ name, colour, alpha });
  names.push(name);
}
if (missing.length) {
  console.log("not in the set:", missing.join(", "));
  process.exit(1);
}

let h = "// GENERATED by tools/avatars/make_avatars.js - do not edit.\n" +
  "// The online play's avatars: icons of game-icons.net (Lorc, Delapouite and contributors, CC BY 3.0),\n" +
  `// each the alpha of a white picture ${AVATAR_SIZE}x${AVATAR_SIZE}, and the colour of its disc (0xRRGGBB).\n` +
  "#ifndef XB_AVATARS_H\n#define XB_AVATARS_H\n\n" +
  `#define AVATAR_SIZE ${AVATAR_SIZE}\n#define AVATAR_COUNT ${out.length}\n\n` +
  "static const unsigned int s_avatarDisc[AVATAR_COUNT] = {\n";
h += out.map((a, i) => `    0x${a.colour.toString(16).padStart(6, "0")}${i + 1 < out.length ? "," : ""}   // ${a.name}`).join("\n") + "\n};\n\n";
h += "static const unsigned char s_avatarAlpha[AVATAR_COUNT][AVATAR_SIZE * AVATAR_SIZE] = {\n";
for (const a of out) {
  h += "  { // " + a.name + "\n";
  for (let i = 0; i < a.alpha.length; i += 32) h += "    " + Array.from(a.alpha.subarray(i, i + 32)).join(",") + ",\n";
  h += "  },\n";
}
h += "};\n\n#endif\n";
fs.writeFileSync(path.join(__dirname, "../../platform/xbox360/xb_avatars.h"), h);
console.log(`wrote xb_avatars.h: ${out.length} avatars, ${(h.length / 1024).toFixed(0)} KB of source`);
