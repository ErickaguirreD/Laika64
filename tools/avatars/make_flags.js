// LAIKA 64 - builds platform/xbox360/xb_country_flags.h: the countries of the online play's profile
// and their flags (flag-icons by Panayiotis Lipiridis, MIT; drawn at FLAG_W x FLAG_H, RGBA).
// The list's order is the profile's (xb_menu.cpp s_countries); its last entry, "Other", has no flag.
// Run from this folder:  npm install && node make_flags.js
const fs = require("fs");
const path = require("path");
const { Resvg } = require("@resvg/resvg-js");

const FLAG_W = 48, FLAG_H = 36;
// [ISO code, name in its own language (UTF-8)]: the Spanish-speaking countries first, then the rest.
const COUNTRIES = [
  ["MX", "México"], ["US", "United States"], ["ES", "España"], ["AR", "Argentina"], ["CO", "Colombia"], ["CL", "Chile"], ["PE", "Perú"],
  ["VE", "Venezuela"], ["EC", "Ecuador"], ["GT", "Guatemala"], ["CU", "Cuba"], ["BO", "Bolivia"], ["DO", "República Dominicana"],
  ["HN", "Honduras"], ["PY", "Paraguay"], ["SV", "El Salvador"], ["NI", "Nicaragua"], ["CR", "Costa Rica"], ["PA", "Panamá"],
  ["UY", "Uruguay"], ["PR", "Puerto Rico"], ["BR", "Brasil"], ["CA", "Canada"], ["FR", "France"], ["DE", "Deutschland"],
  ["IT", "Italia"], ["PT", "Portugal"], ["GB", "United Kingdom"], ["RU", "Россия"], ["JP", "Japan"], ["KR", "Korea"],
  ["CN", "China"], ["AU", "Australia"], ["NL", "Nederland"], ["PL", "Polska"], ["SE", "Sverige"], ["TR", "Türkiye"],
  ["SA", "Saudi Arabia"], ["EG", "Egypt"], ["MA", "Morocco"], ["IN", "India"], ["PH", "Philippines"],
];
const dir = path.join(__dirname, "node_modules/flag-icons/flags/4x3");
let h = "// GENERATED by tools/avatars/make_flags.js - do not edit.\n" +
  "// The online play's countries and their flags (flag-icons, Panayiotis Lipiridis, MIT), RGBA " + FLAG_W + "x" + FLAG_H + ".\n" +
  "#ifndef XB_COUNTRY_FLAGS_H\n#define XB_COUNTRY_FLAGS_H\n\n" +
  `#define FLAG_W ${FLAG_W}\n#define FLAG_H ${FLAG_H}\n#define FLAG_COUNTRIES ${COUNTRIES.length}\n\n` +
  "struct CountryFlag { const char *code, *name; };\n" +
  "static const CountryFlag s_flagCountries[FLAG_COUNTRIES] = {\n" +
  COUNTRIES.map(([c, n]) => `    { "${c}", "${Buffer.from(n, "utf8").toString("latin1").replace(/[\x80-\xff]/g, (ch) => "\\x" + ch.charCodeAt(0).toString(16) + '" "')}" }`).join(",\n") +
  "\n};\n\nstatic const unsigned char s_flagRgba[FLAG_COUNTRIES][FLAG_W * FLAG_H * 4] = {\n";
for (const [code] of COUNTRIES) {
  const svg = fs.readFileSync(path.join(dir, code.toLowerCase() + ".svg"), "utf8");
  const png = new Resvg(svg, { fitTo: { mode: "width", value: FLAG_W } }).render();
  if (png.width !== FLAG_W || png.height !== FLAG_H) throw new Error(code + ": " + png.width + "x" + png.height);
  const px = png.pixels;
  h += "  { // " + code + "\n";
  for (let i = 0; i < px.length; i += 48) h += "    " + Array.from(px.subarray(i, i + 48)).join(",") + ",\n";
  h += "  },\n";
}
h += "};\n\n#endif\n";
fs.writeFileSync(path.join(__dirname, "../../platform/xbox360/xb_country_flags.h"), h);
console.log(`wrote xb_country_flags.h: ${COUNTRIES.length} flags, ${(h.length / 1024).toFixed(0)} KB of source`);
