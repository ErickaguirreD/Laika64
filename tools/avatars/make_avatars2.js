// LAIKA 64 - builds platform/xbox360/xb_avatars2.h: the online play's colour avatars (2.2.2), in sets the
// avatar picker shows as tabs after the classic icons (xb_avatars.h):
//   Pixel Art  - DiceBear "Pixel Art" (DiceBear, CC0 1.0)
//   Robots     - DiceBear "Bottts", a remix of Bottts by Pablo Stanley (free for personal and commercial use)
//   Characters - Twemoji (Twitter, CC BY 4.0) on a coloured disc
// Each one a round PNG of AVATAR2_SIZE (decoded on the console with h64_png_decode). The server keeps them
// as avatar numbers from AVATAR2_BASE (the classic ones 0-62, 63 the team's). Run from this folder:
//     npm install && node make_avatars2.js
const fs = require("fs");
const path = require("path");
const { Resvg } = require("@resvg/resvg-js");

const AVATAR2_SIZE = 64, PER_SET = 24;
// The discs' colours, in turn (pastel for the DiceBear sets, deep for the characters).
const PASTEL = ["b6e3f4", "c0aede", "d1d4f9", "ffd5dc", "ffdfbf", "c1f4c5", "fdf0a6", "a7f3d0"];
const DEEP = ["1f8a8a", "6b2f8f", "1f6f7a", "8f2f4f", "2f7a3f", "8a5a1f", "2f4f8f", "5a2f2f"];
// Seeds that give a varied set (fixed: the same pictures every build).
const SEEDS = ["Mario", "Luna", "Rex", "Kira", "Bolt", "Nova", "Zelda", "Fox", "Pixel", "Turbo", "Echo", "Blaze",
  "Koko", "Rayo", "Ninja", "Taco", "Vega", "Milo", "Zap", "Kaiju", "Orbit", "Coco", "Duke", "Saga"];
// space invader, alien, robot, ghost, skull, pumpkin, dragon, T-rex, mage, ninja, vampire, zombie,
// superhero, supervillain, elf, genie, ogre, clown, devil, fox, wolf, dragon face, unicorn, octopus
const CHARACTERS = ["1f47e", "1f47d", "1f916", "1f47b", "1f480", "1f383", "1f409", "1f996", "1f9d9", "1f977", "1f9db", "1f9df",
  "1f9b8", "1f9b9", "1f9dd", "1f9de", "1f479", "1f921", "1f608", "1f98a", "1f43a", "1f432", "1f984", "1f419"];

async function main() {
  const { createAvatar } = await import("@dicebear/core");
  const { pixelArt, bottts } = await import("@dicebear/collection");
  const twemoji = path.dirname(require.resolve("@twemoji/svg/package.json"));
  const png = (svg) => Buffer.from(new Resvg(svg, { fitTo: { mode: "width", value: AVATAR2_SIZE }, background: "rgba(0,0,0,0)" }).render().asPng());
  const sets = [];
  for (const [name, style] of [["Pixel Art", pixelArt], ["Robots", bottts]])
    sets.push({ name, pics: SEEDS.map((s, i) => png(createAvatar(style, { seed: s + i, size: AVATAR2_SIZE, backgroundColor: [PASTEL[i % PASTEL.length]], radius: 50 }).toString())) });
  sets.push({
    name: "Characters", pics: CHARACTERS.map((code, i) => {
      // The emoji's own drawing (viewBox 36) inside a disc, a margin around it.
      const body = fs.readFileSync(path.join(twemoji, code + ".svg"), "utf8").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
      return png(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36" width="${AVATAR2_SIZE}" height="${AVATAR2_SIZE}">` +
        `<circle cx="18" cy="18" r="18" fill="#${DEEP[i % DEEP.length]}"/><g transform="translate(5.4 5.4) scale(0.7)">${body}</g></svg>`);
    })
  });
  for (const s of sets) if (s.pics.length !== PER_SET) throw new Error(s.name + ": " + s.pics.length);

  let h = "// GENERATED by tools/avatars/make_avatars2.js - do not edit.\n" +
    "// The online play's colour avatars, round PNGs " + AVATAR2_SIZE + "x" + AVATAR2_SIZE + " in sets of " + PER_SET + ":\n" +
    "// Pixel Art (DiceBear, CC0 1.0), Robots (Bottts by Pablo Stanley, free for personal and commercial use),\n" +
    "// Characters (Twemoji, Twitter, CC BY 4.0).\n" +
    "#ifndef XB_AVATARS2_H\n#define XB_AVATARS2_H\n\n" +
    `#define AVATAR2_SIZE ${AVATAR2_SIZE}\n#define AVATAR2_BASE 64   // their avatar numbers: from here (the classic ones below, 63 the team's)\n` +
    `#define AVATAR2_PER_SET ${PER_SET}\n#define AVATAR2_SETS ${sets.length}\n#define AVATAR2_COUNT ${sets.length * PER_SET}\n\n`;
  let n = 0, total = 0;
  for (const s of sets)
    for (const p of s.pics) {
      h += `static const unsigned char s_avatar2_${n}[${p.length}] = {   // ${s.name}\n`;
      for (let i = 0; i < p.length; i += 32) h += "    " + Array.from(p.subarray(i, i + 32)).join(",") + ",\n";
      h += "};\n";
      n++; total += p.length;
    }
  h += "\nstatic const unsigned char *const s_avatar2Png[AVATAR2_COUNT] = {\n" +
    Array.from({ length: n }, (_, i) => `    s_avatar2_${i}`).join(",\n") + "\n};\n";
  h += "static const unsigned int s_avatar2PngSize[AVATAR2_COUNT] = {\n" +
    Array.from({ length: n }, (_, i) => `    sizeof(s_avatar2_${i})`).join(",\n") + "\n};\n\n#endif\n";
  fs.writeFileSync(path.join(__dirname, "../../platform/xbox360/xb_avatars2.h"), h);
  console.log(`wrote xb_avatars2.h: ${n} avatars, ${(total / 1024).toFixed(0)} KB of PNG`);
}
main().catch((e) => { console.error(e); process.exit(1); });
