#!/usr/bin/env python3
"""LAIKA 64 - the setup assistant's reference picture (platform/xbox360/xb_wizref.h).

An original landscape, drawn here (no image files): a dusk sky, the sun and its
glow, three ranges of mountains fading into the haze, a lake that mirrors them,
pines on the shore. The Picture step shows it at the chosen resolution (its
pixels as big as that leaves them), colour style and brightness.

    python platform/xbox360/tools/gen_wizref.py [preview.png]
"""
import io
import math
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_wizref.h")
W, H = 960, 540          # drawn at, then halved
OUT_W, OUT_H = 480, 270
HORIZON = int(H * 0.62)


def noise1d(n, seed, octaves):
    rng = np.random.RandomState(seed)
    out = np.zeros(n)
    for o in range(octaves):
        pts = 4 * 2 ** o + 1
        v = rng.rand(pts)
        xs = np.linspace(0, pts - 1, n)
        out += np.interp(xs, np.arange(pts), v) / 2 ** o
    return out / out.max()


def lerp(a, b, t):
    return tuple(int(a[k] + (b[k] - a[k]) * t) for k in range(3))


def main():
    img = Image.new("RGB", (W, H))
    px = np.zeros((H, W, 3), np.float32)
    # Sky: deep blue at the top to a warm orange at the horizon.
    for y in range(HORIZON):
        t = y / HORIZON
        c = np.array(lerp((22, 34, 78), (110, 78, 140), min(1, t * 1.4))) if t < 0.7 else \
            np.array(lerp((110, 78, 140), (250, 160, 90), (t - 0.7) / 0.3))
        px[y] = c
    # The sun and its glow.
    sx, sy = W * 0.66, HORIZON - 150
    yy, xx = np.mgrid[0:H, 0:W]
    d = np.sqrt((xx - sx) ** 2 + ((yy - sy) * 1.1) ** 2)
    glow = np.exp(-d / 140.0)[..., None] * np.array([255, 170, 90]) * 0.55
    px[:HORIZON] += glow[:HORIZON]
    px[(d < 34) & (yy < HORIZON)] = [255, 236, 190]
    # Mountains: three ranges, further ones lighter (haze).
    # Peaks: the noise folded (abs) into ridges; nearer ranges higher and darker.
    ranges = [(95, 7, (132, 98, 150)), (125, 11, (86, 66, 116)), (150, 19, (44, 38, 70))]
    for height, seed, col in ranges:
        prof = noise1d(W, seed, 6)
        ridge = 1.0 - np.abs(prof * 2.0 - 1.0)
        base = HORIZON - height * (0.35 + 0.65 * ridge ** 1.6)
        for x in range(W):
            y0 = int(max(0, base[x]))
            px[y0:HORIZON, x] = col
    # The lake: the sky and mountains above, mirrored, darker, with ripples.
    refl = px[:HORIZON][::-1][:H - HORIZON].copy()
    for y in range(H - HORIZON):
        shift = int(3 * math.sin(y * 0.55))
        refl[y] = np.roll(refl[y], shift, axis=0)
    px[HORIZON:] = refl * 0.72 + np.array([10, 18, 40]) * 0.28
    # Light on the water under the sun.
    for y in range(HORIZON, H):
        wv = 18 + (y - HORIZON) * 0.6
        a = np.exp(-((xx[0] - sx) / wv) ** 2) * (0.6 if (y // 3) % 2 else 0.25)
        px[y] += (a[:, None] * np.array([255, 190, 120]))
    img = Image.fromarray(px.clip(0, 255).astype(np.uint8))
    d = ImageDraw.Draw(img)
    # Pines on the left shore, dark against the lake.
    rng = np.random.RandomState(3)
    for i in range(26):
        x = rng.randint(-20, int(W * 0.30))
        hgt = rng.randint(60, 150)
        base = HORIZON + rng.randint(4, 30)
        for k in range(5):
            w = hgt * (0.42 - k * 0.07)
            y = base - hgt * k / 5
            d.polygon([(x - w / 2, y), (x + w / 2, y), (x, y - hgt * 0.32)], fill=(12, 16, 26))
        d.rectangle([x - 3, base, x + 3, base + 10], fill=(10, 12, 18))
    shore = [(0, HORIZON + 10)] + [(x, HORIZON + 14 + 10 * math.sin(x * 0.03) + x * 0.35) for x in range(0, int(W * 0.42), 12)] + \
            [(int(W * 0.42), H), (0, H)]
    d.polygon(shore, fill=(12, 16, 26))   # the shore, sloping into the lake
    img = img.filter(ImageFilter.GaussianBlur(0.6)).resize((OUT_W, OUT_H), Image.LANCZOS)
    if len(sys.argv) > 1:
        img.save(sys.argv[1])
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    lines = ["// LAIKA 64 - the setup assistant's reference picture (PNG, %dx%d). GENERATED by platform/xbox360/tools/gen_wizref.py: do not edit." % (OUT_W, OUT_H),
             "#ifndef XB_WIZREF_H", "#define XB_WIZREF_H", "",
             "#define WIZREF_W %d" % OUT_W, "#define WIZREF_H %d" % OUT_H, "",
             "static const unsigned char s_wizRefPng[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % v for v in data[i:i + 24]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d bytes" % (OUT, len(data)))


if __name__ == "__main__":
    main()
