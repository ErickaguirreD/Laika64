#!/usr/bin/env python3
"""LAIKA 64 - writes platform/xbox360/xb_profile.h, the profile picture beside
ErickaguirreD on the Credits page, from luna.jpg (the moon on black).

The picture is cropped to a square around the moon (found from its bright
pixels) and made PROFILE_SIZE wide; xb_menu.cpp draws it as a circle (UiImage
with a radius of half its size), so no alpha is needed. Kept as PNG bytes:
xb_menu.cpp decodes it with h64_png_decode.

    python platform/xbox360/tools/gen_profile.py luna.jpg
"""
import io
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_profile.h")
PROFILE_SIZE = 160


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: gen_profile.py luna.jpg")
    img = Image.open(sys.argv[1]).convert("RGB")
    # The moon's disc: its top and bottom from the bright pixels (the whole height is
    # lit), its left from the lit limb; the right side is in shadow, so the width
    # comes from the height (a circle).
    lum = np.asarray(img.convert("L")).astype(np.float32)
    ys, xs = np.nonzero(lum > 40)
    y0, y1 = np.percentile(ys, [0.1, 99.9])
    x0 = np.percentile(xs, 0.1)
    half = (y1 - y0) * 0.5 * 1.06   # a little black around it
    cx, cy = x0 + (y1 - y0) * 0.5, (y0 + y1) * 0.5
    box = tuple(int(round(v)) for v in (cx - half, cy - half, cx + half, cy + half))
    img = img.crop(box).resize((PROFILE_SIZE, PROFILE_SIZE), Image.LANCZOS)
    rgba = img.convert("RGBA")
    buf = io.BytesIO()
    rgba.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    lines = ["// LAIKA 64 - the Credits page's profile picture (PNG, %dx%d). GENERATED by platform/xbox360/tools/gen_profile.py: do not edit." % (PROFILE_SIZE, PROFILE_SIZE),
             "#ifndef XB_PROFILE_H", "#define XB_PROFILE_H", "",
             "#define UI_PROFILE_SIZE %d" % PROFILE_SIZE, "",
             "static const unsigned char s_profilePng[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % v for v in data[i:i + 24]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %dx%d, %d bytes, crop %s" % (OUT, PROFILE_SIZE, PROFILE_SIZE, len(data), box))


if __name__ == "__main__":
    main()
