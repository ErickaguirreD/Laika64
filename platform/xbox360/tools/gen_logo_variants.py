#!/usr/bin/env python3
"""Harissa64 V2 - writes platform/xbox360/xb_logo_variants.h: the LAIKA 64 logo in
the menus' edge colours (blue, green, red, purple, gold), drawn by UiBrand when
Interface > Borders and panels > Border colour is one of those (xb_ui.cpp).

From "LAIKA VARIANTES.png" (two columns, three rows: the original, blue, green,
red, purple, gold): each cell's logo is cut out, the stray specks of its glow
(small islands of colour around it) dropped, cropped and made LOGO_H high.
Kept as PNG bytes (h64_png_decode).

    python platform/xbox360/tools/gen_logo_variants.py "LAIKA VARIANTES.png" [preview.png]
"""
import io
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_logo_variants.h")
LOGO_H = 192
# The cells (column, row) of each variant written, in UI_LOGO_VAR_* order.
CELLS = [("BLUE", 1, 0), ("GREEN", 0, 1), ("RED", 1, 1), ("PURPLE", 0, 2), ("GOLD", 1, 2)]


def islands(mask):
    """Labels of the 4-connected islands of `mask` and their sizes."""
    from collections import deque
    h, w = mask.shape
    lab = np.zeros((h, w), np.int32)
    sizes = [0]
    for y0, x0 in zip(*np.nonzero(mask)):
        if lab[y0, x0]:
            continue
        n = len(sizes)
        q = deque([(y0, x0)])
        lab[y0, x0] = n
        cnt = 0
        while q:
            y, x = q.popleft()
            cnt += 1
            for yy, xx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
                if 0 <= yy < h and 0 <= xx < w and mask[yy, xx] and not lab[yy, xx]:
                    lab[yy, xx] = n
                    q.append((yy, xx))
        sizes.append(cnt)
    return lab, sizes


def cut(img):
    a = np.asarray(img)[..., 3]
    small = img.resize((img.width // 4, img.height // 4), Image.BILINEAR)
    sa = np.asarray(small)[..., 3] > 170
    lab, sizes = islands(sa)
    keep = np.zeros_like(sa)
    for i in range(1, len(sizes)):
        if sizes[i] >= 120:   # the emblem, the letters; not the specks
            keep |= lab == i
    m = Image.fromarray((keep * 255).astype(np.uint8)).resize(img.size, Image.BILINEAR)
    m = m.filter(ImageFilter.MaxFilter(13)).filter(ImageFilter.GaussianBlur(6))   # a soft halo for the glow
    mk = np.asarray(m).astype(np.float32) / 255.0
    # The islands left out, gone even inside the halo (the tip above sits close to the emblem).
    drop = Image.fromarray(((sa & ~keep) * 255).astype(np.uint8)).resize(img.size, Image.BILINEAR).filter(ImageFilter.MaxFilter(9))
    mk *= 1.0 - np.asarray(drop).astype(np.float32) / 255.0
    rgba = np.asarray(img).astype(np.float32)
    rgba[..., 3] = a * mk
    out = Image.fromarray(rgba.clip(0, 255).astype(np.uint8), "RGBA")
    ys, xs = np.nonzero(np.asarray(out)[..., 3] > 8)
    out = out.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    return out.resize((round(out.width * LOGO_H / out.height), LOGO_H), Image.LANCZOS)


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: gen_logo_variants.py variants.png [preview.png]")
    sheet = Image.open(sys.argv[1]).convert("RGBA")
    cw, ch = sheet.width // 2, sheet.height // 3
    alpha = np.asarray(sheet)[..., 3]
    logos = []
    for name, col, row in CELLS:
        # The rows between logos where their emblems' points meet (they touch through
        # the glow): the narrowest row near each third, in this column.
        solid = (alpha[:, col * cw:(col + 1) * cw] > 170).sum(1)
        cuts = [0] + [b - 50 + int(np.argmin(solid[b - 50:b + 50])) for b in (ch, 2 * ch)] + [sheet.height]
        logos.append((name, cut(sheet.crop((col * cw, cuts[row], (col + 1) * cw, cuts[row + 1])))))
    if len(sys.argv) > 2:
        pw = max(l.width for _, l in logos)
        prev = Image.new("RGBA", (pw, LOGO_H * len(logos)), (24, 26, 34, 255))
        for i, (_, l) in enumerate(logos):
            prev.alpha_composite(l, (0, i * LOGO_H))
        prev.save(sys.argv[2])
    lines = ["// Harissa64 V2 - the LAIKA 64 logo in the edge colours (PNG). GENERATED by platform/xbox360/tools/gen_logo_variants.py: do not edit.",
             "#ifndef XB_LOGO_VARIANTS_H", "#define XB_LOGO_VARIANTS_H", "",
             "enum { %s, UI_LOGO_VAR_COUNT };" % ", ".join("UI_LOGO_VAR_%s" % n for n, _, _ in CELLS), ""]
    names = []
    for name, l in logos:
        buf = io.BytesIO()
        l.save(buf, "PNG", optimize=True)
        data = buf.getvalue()
        var = "s_logoVar%s" % name.capitalize()
        names.append((var, len(data), l.width, l.height))
        lines.append("static const unsigned char %s[%d] = {" % (var, len(data)))
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join("0x%02X" % v for v in data[i:i + 24]) + ",")
        lines += ["};", ""]
    lines.append("static const unsigned char *const s_logoVarPng[UI_LOGO_VAR_COUNT] = { %s };" % ", ".join(n for n, _, _, _ in names))
    lines.append("static const unsigned s_logoVarSize[UI_LOGO_VAR_COUNT] = { %s };" % ", ".join(str(s) for _, s, _, _ in names))
    lines.append("static const int s_logoVarW[UI_LOGO_VAR_COUNT] = { %s };" % ", ".join(str(w) for _, _, w, _ in names))
    lines += ["", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %s" % (OUT, ", ".join("%s %dx%d %d KB" % (n, w, h, s >> 10) for n, s, w, h in names)))


if __name__ == "__main__":
    main()
