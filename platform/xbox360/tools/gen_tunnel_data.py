#!/usr/bin/env python3
"""LAIKA 64 - writes platform/xbox360/xb_tunnel_data.h: the "data" on the walls of the tunnel that opens Online
play (xb_menu.cpp online_intro). Eight lanes of 1024 x 64 pixels, one under the other: words of the network and of
LAIKA, numbers and bits, white on transparent (the menu tints them), in Orbitron (third_party/fonts/orbitron, OFL).
Each lane is drawn along the tunnel, eight of its slices a lane; the text runs on from its end into its start.
Kept as PNG bytes (h64_png_decode).

    python platform/xbox360/tools/gen_tunnel_data.py [preview.png]
"""
import io
import os
import random
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_tunnel_data.h")
FONT = os.path.join(ROOT, "third_party", "fonts", "orbitron", "Orbitron[wght].ttf")
W, LANE, LANES = 1024, 64, 8
BIG = ["INTERNET", "LAIKA 64", "ONLINE", "NETPLAY", "WWW", "HTTP://", "DATA", "P2P", "TCP/IP", "SYNC", "LOBBY", "PING"]
SMALL = ["information", "packet", "upload", "download", "0x7F3A", "0xC0DE", "192.168", "player 2", "e-mail", "stream",
         "10110010", "01001100", "frame 60", "ack", "rtt 32ms", "uplink", "socket", "N64"]


def font(size, weight):
    f = ImageFont.truetype(FONT, size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f


def lane(rng, k):
    """One lane: big words on its middle, or two rows of small ones (every third lane), wrapping around."""
    img = Image.new("L", (W * 2, LANE), 0)
    d = ImageDraw.Draw(img)
    x0 = x = rng.randint(10, 120)
    end = W + x0 - 24   # what runs past W comes back at the start: never over its first word
    small = k % 3 == 2
    while True:
        if small:
            f = font(17, 700)
            words = [rng.choice(SMALL) for _ in range(2)]
            ww = max(int(d.textlength(w, font=f)) + row * 37 for row, w in enumerate(words))
            if x + ww > end:
                break
            for row, cy in enumerate((LANE * 0.3, LANE * 0.72)):
                d.text((x + row * 37, cy), words[row], fill=230, font=f, anchor="lm")
            x += max(ww + 40, 190 + rng.randint(0, 60))
        else:
            f = font(rng.choice((30, 36, 42, 46)), 900)
            word = rng.choice(BIG)
            ww = int(d.textlength(word, font=f))
            if x + ww > end:
                break
            d.text((x, LANE * 0.5), word, fill=255, font=f, anchor="lm")
            x += ww + rng.randint(40, 110)
            f2 = font(15, 600)
            w2 = rng.choice(SMALL)
            if rng.random() < 0.5 and x + d.textlength(w2, font=f2) <= end:
                d.text((x, LANE * 0.5), w2, fill=200, font=f2, anchor="lm")
                x += int(d.textlength(w2, font=f2)) + rng.randint(30, 70)
    # What ran past the end goes on at the start (the lane is drawn round and round).
    left = img.crop((0, 0, W, LANE))
    over = img.crop((W, 0, W * 2, LANE))
    return Image.fromarray(np.maximum(np.asarray(left), np.asarray(over)))


def main():
    rng = random.Random(64)
    alpha = Image.new("L", (W, LANE * LANES), 0)
    for k in range(LANES):
        alpha.paste(lane(rng, k), (0, k * LANE))
    img = Image.merge("RGBA", (Image.new("L", alpha.size, 255),) * 3 + (alpha,))
    if len(sys.argv) == 2:
        bg = Image.new("RGB", img.size, (10, 20, 30))
        bg.paste(Image.new("RGB", img.size, (60, 220, 255)), (0, 0), alpha)
        bg.save(sys.argv[1])
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    lines = ["// LAIKA 64 - the tunnel's data (PNG, %dx%d: %d lanes). GENERATED by platform/xbox360/tools/gen_tunnel_data.py: do not edit." % (W, LANE * LANES, LANES),
             "#ifndef XB_TUNNEL_DATA_H", "#define XB_TUNNEL_DATA_H", "",
             "#define TUNNEL_DATA_LANES %d" % LANES, "",
             "static const unsigned char s_tunnelDataPng[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d bytes" % (OUT, len(data)))


if __name__ == "__main__":
    main()
