#!/usr/bin/env python3
"""Harissa64 V2 - writes platform/xbox360/xb_pad.h, the N64 controller picture of
the Controls page (draw_n64_pad), from n64.jpg (a grey controller on red).

The red background (only what touches the border: Start stays red) becomes
transparent, its anti-aliased edge un-mixed from the red; the maker's logo on
the top is painted over with the body's own grain from just below it. The
picture is cropped to the controller and made PAD_W wide. Kept as PNG bytes:
xb_menu.cpp decodes it with h64_png_decode. UI_PAD_SRC_* say where the crop
was in the source picture, so the buttons can be placed in its coordinates.

    python platform/xbox360/tools/gen_pad.py n64.jpg [preview.png]
"""
import io
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_pad.h")
PAD_W = 560
LOGO = (612, 268, 892, 340)   # x0, y0, x1, y1 of the logo's plate in the 1500x1500 source


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: gen_pad.py n64.jpg [preview.png]")
    src = np.asarray(Image.open(sys.argv[1]).convert("RGB")).astype(np.float32)
    h, w, _ = src.shape
    r, g, b = src[..., 0], src[..., 1], src[..., 2]
    redness = r - (g + b) * 0.5

    # The background: red pixels reached from the border (a flood fill).
    red = (redness > 90) & (g < 110)
    bg = np.zeros((h, w), bool)
    stack = [(0, x) for x in range(w)] + [(h - 1, x) for x in range(w)] + [(y, 0) for y in range(h)] + [(y, w - 1) for y in range(h)]
    while stack:
        y, x = stack.pop()
        if bg[y, x] or not red[y, x]:
            continue
        bg[y, x] = True
        if y > 0: stack.append((y - 1, x))
        if y < h - 1: stack.append((y + 1, x))
        if x > 0: stack.append((y, x - 1))
        if x < w - 1: stack.append((y, x + 1))

    # The edge: pixels next to the background, part red. Their alpha from how red
    # they are (the background's own redness nearby), their colour un-mixed.
    near = np.zeros_like(bg)
    for dy in (-2, -1, 0, 1, 2):
        for dx in (-2, -1, 0, 1, 2):
            near |= np.roll(np.roll(bg, dy, 0), dx, 1)
    edge = near & ~bg
    bgCol = np.array([src[..., c][bg].mean() for c in range(3)], np.float32)
    bgRed = bgCol[0] - (bgCol[1] + bgCol[2]) * 0.5
    alpha = np.ones((h, w), np.float32)
    alpha[bg] = 0.0
    a = np.clip(1.0 - redness / bgRed, 0.0, 1.0)
    alpha[edge] = a[edge]
    out = src.copy()
    am = np.maximum(alpha, 1e-3)[..., None]
    un = (src - (1.0 - alpha)[..., None] * bgCol) / am
    out[edge] = np.clip(un[edge], 0, 255)
    # Grey body edges: no red left in what stays.
    keep = edge & (alpha > 0)
    grey = out[..., 1:3].mean(axis=2)
    out[..., 0][keep] = np.minimum(out[..., 0][keep], grey[keep] + 12)

    # The logo: each column between the body above and below its plate, with
    # the grain of the body just under it.
    # The body above and below, averaged over a few lines and 15 columns (one
    # pixel each made every column a stripe of its own).
    x0, y0, x1, y1 = LOGO
    hh = y1 - y0
    above = out[y0 - 10:y0 - 2].mean(axis=0).copy()
    below = out[y1 + 2:y1 + 10].mean(axis=0).copy()
    for x in range(x0, x1):
        top, bot = above[x - 7:x + 8].mean(axis=0), below[x - 7:x + 8].mean(axis=0)
        patch = out[y1 + 8:y1 + 8 + hh, x]
        grain = patch - patch.mean(axis=0)
        for k in range(hh):
            t = (k + 0.5) / hh
            out[y0 + k, x] = top * (1 - t) + bot * t + grain[k] * 0.8
    # Soften the seams of the painted box (a 3-pixel blend at its sides).
    for x in list(range(x0 - 3, x0 + 3)) + list(range(x1 - 3, x1 + 3)):
        col = out[y0:y1, x - 1:x + 2].mean(axis=1)
        out[y0:y1, x] = col

    # Crop to the controller, then scale.
    ys, xs = np.nonzero(alpha > 0.02)
    cx0, cy0, cx1, cy1 = xs.min() - 2, ys.min() - 2, xs.max() + 3, ys.max() + 3
    rgba = np.dstack([out, alpha[..., None] * 255.0]).clip(0, 255).astype(np.uint8)[cy0:cy1, cx0:cx1]
    img = Image.fromarray(rgba, "RGBA")
    ph = round(img.height * PAD_W / img.width)
    img = img.resize((PAD_W, ph), Image.LANCZOS)
    if len(sys.argv) > 2:
        prev = Image.new("RGBA", img.size, (24, 26, 34, 255))
        prev.alpha_composite(img)
        prev.save(sys.argv[2])
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    lines = ["// Harissa64 V2 - the N64 controller picture (PNG, %dx%d). GENERATED by platform/xbox360/tools/gen_pad.py: do not edit." % (PAD_W, ph),
             "#ifndef XB_PAD_H", "#define XB_PAD_H", "",
             "#define UI_PAD_W %d" % PAD_W, "#define UI_PAD_H %d" % ph,
             "// The picture is this part of the 1500x1500 source (button places are given in the source's pixels).",
             "#define UI_PAD_SRC_X %d" % cx0, "#define UI_PAD_SRC_Y %d" % cy0,
             "#define UI_PAD_SRC_W %d" % (cx1 - cx0), "#define UI_PAD_SRC_H %d" % (cy1 - cy0), "",
             "static const unsigned char s_padPng[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % v for v in data[i:i + 24]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %dx%d, %d bytes, crop %d,%d %dx%d" % (OUT, PAD_W, ph, len(data), cx0, cy0, cx1 - cx0, cy1 - cy0))


if __name__ == "__main__":
    main()
