#!/usr/bin/env python3
"""LAIKA 64 - Laika's sounds (xb_laika_bark.h), kept in the executable so they are there after an update made from the
console (which replaces default.xex only), resampled to the interface sounds' 48 kHz, 16-bit mono:
- assets/assistant/laika_bark.wav: her double bark ("Dog Bark 2.wav" of pauliuw's "Dog sounds", OpenGameArt, CC0, twice
  0.45 s apart, the second a little lower), made to sound as a Super Nintendo would play it (a 16 kHz sample with a
  4-bit grain per block, Gaussian interpolation, echo);
- assets/assistant/laika_angry.wav: angry - a growl (synthesized: a low voice in pulses through a dog's formants) into
  two hard barks (the same recording lower and pushed into distortion, at 0.71 and 1.01 s), in the same style.

    python platform/xbox360/tools/gen_laika_bark.py
"""
import os
import wave

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_laika_bark.h")
RATE = 48000
SOUNDS = [("BARK", "s_laikaBark", "laika_bark.wav"), ("ANGRY", "s_laikaAngry", "laika_angry.wav")]


def read(path):
    w = wave.open(path)
    x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32)
    if w.getnchannels() > 1:
        x = x.reshape(-1, w.getnchannels()).mean(1)
    n = int(len(x) * RATE / w.getframerate())
    y = np.interp(np.arange(n) * w.getframerate() / RATE, np.arange(len(x)), x)
    return np.clip(y, -32767, 32767).astype(np.int16)


def main():
    lines = ["// LAIKA 64 - Laika's sounds (48 kHz, 16-bit mono). GENERATED by platform/xbox360/tools/gen_laika_bark.py",
             "// from assets/assistant/laika_bark.wav and laika_angry.wav (\"Dog Bark 2\" of pauliuw's \"Dog sounds\",",
             "// OpenGameArt, CC0, in a Super Nintendo style; the growl synthesized): do not edit.",
             "#ifndef XB_LAIKA_BARK_H", "#define XB_LAIKA_BARK_H", ""]
    for name, var, src in SOUNDS:
        y = read(os.path.join(ROOT, "assets", "assistant", src))
        lines += ["#define LAIKA_%s_LEN %d" % (name, len(y)), "static const short %s[LAIKA_%s_LEN] = {" % (var, name)]
        for i in range(0, len(y), 16):
            lines.append("    " + ",".join(str(int(v)) for v in y[i:i + 16]) + ",")
        lines += ["};", ""]
        print("%s: %d samples (%.2f s)" % (src, len(y), len(y) / RATE))
    lines += ["#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote " + OUT)


if __name__ == "__main__":
    main()
