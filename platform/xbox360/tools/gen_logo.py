#!/usr/bin/env python3
"""Harissa64 V2 - writes platform/xbox360/xb_logo.h, the LAIKA 64 logo drawn by
UiBrand, from a PNG (kept as PNG bytes: xb_ui.cpp decodes it with h64_png_decode).

The PNG is the logo with its transparent margins cropped, 96 pixels high (1.5x
the size the ROM browser shows it at, so it stays sharp).

    python platform/xbox360/tools/gen_logo.py logo.png
"""
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "platform", "xbox360", "xb_logo.h")


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen_logo.py logo.png")
    data = open(sys.argv[1], "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s is not a PNG" % sys.argv[1])
    w, h = struct.unpack(">II", data[16:24])
    lines = ["// Harissa64 V2 - the LAIKA 64 logo (PNG, %dx%d). GENERATED by platform/xbox360/tools/gen_logo.py: do not edit." % (w, h),
             "#ifndef XB_LOGO_H", "#define XB_LOGO_H", "",
             "#define UI_LAIKA_LOGO_W %d" % w, "#define UI_LAIKA_LOGO_H %d" % h, "",
             "static const unsigned char s_laikaLogoPng[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %dx%d, %d bytes" % (OUT, w, h, len(data)))


if __name__ == "__main__":
    main()
