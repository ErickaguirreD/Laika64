#!/usr/bin/env python3
"""Generates core/cart/h64_romdb.inc: every ROM mupen64plus's catalogue knows
(header CRC1, CRC2), with its GoodN64 name and what it is - an original dump,
a translation, a hack, a bad dump or another kind of modified dump - from the
name's GoodN64 codes ([!] verified, [T+...] translation, [h...] or "Hack" a
hack, [b] bad, [o] [f] [t] [p] overdump, fix, trainer, pirate; "(PD)" public
domain). Online play shows by it what a room's ROM is, and the detailed view
what a ROM of the list is (h64_rom_catalogue).

Source: mupen64plus-core's data/mupen64plus.ini (GPL v2, see THIRD_PARTY.md).
Run (from the repository root):
    python tests/scripts/gen_romdb.py [mupen64plus.ini]
Without a file it downloads mupen64plus-core master's.
"""
import os
import re
import sys
import urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
URL = "https://raw.githubusercontent.com/mupen64plus/mupen64plus-core/master/data/mupen64plus.ini"
KINDS = ["H64_ROMKIND_ORIGINAL", "H64_ROMKIND_TRANSLATION", "H64_ROMKIND_HACK", "H64_ROMKIND_BAD", "H64_ROMKIND_OTHER",
         "H64_ROMKIND_HOMEBREW"]


def kind_of(name):
    low = name.lower()
    if re.search(r"\[h\d*[a-z]*\]|\[h\d|hack\b", low):
        return 2
    if "[t+" in low or "[t-" in low:
        return 1
    if re.search(r"\[b\d*\]", low):
        return 3
    if re.search(r"\[(o|f|t|p)\d*\]", low):
        return 4
    if "(pd)" in low:
        return 5
    return 0


def main():
    if len(sys.argv) > 1:
        text = open(sys.argv[1], encoding="latin-1").read()
    else:
        text = urllib.request.urlopen(URL).read().decode("latin-1")
    entries, cur = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            cur = entries.setdefault(line[1:-1], {})
        elif cur is not None and "=" in line and not line.startswith(";"):
            k, v = line.split("=", 1)
            cur[k.strip()] = v.strip()
    rows = {}
    for e in entries.values():
        crc, name = e.get("CRC"), e.get("GoodName")
        if not crc or not name:
            continue
        c1, c2 = (int(x, 16) for x in crc.split())
        k = kind_of(name)
        # one pair, several names (the same dump listed twice): the original's first
        if (c1, c2) not in rows or k < rows[(c1, c2)][0]:
            rows[(c1, c2)] = (k, name)
    out = ["// Generated by tests/scripts/gen_romdb.py from mupen64plus's ROM catalogue: do not edit.",
           "// { header CRC1, header CRC2, what it is, GoodN64 name }, sorted."]
    for (c1, c2), (k, name) in sorted(rows.items()):
        safe = name.encode("ascii", "replace").decode("ascii").replace("\\", "/").replace('"', "'")[:63]
        out.append('{ 0x%08Xu, 0x%08Xu, %s, "%s" },' % (c1, c2, KINDS[k], safe))
    path = os.path.join(ROOT, "core", "cart", "h64_romdb.inc")
    open(path, "w", newline="\n", encoding="ascii").write("\n".join(out) + "\n")
    counts = [sum(1 for k, _ in rows.values() if k == i) for i in range(len(KINDS))]
    print("wrote %s (%d entries: %s)" % (path, len(rows), ", ".join("%s %d" % (KINDS[i][12:].lower(), counts[i]) for i in range(len(KINDS)))))


if __name__ == "__main__":
    main()
